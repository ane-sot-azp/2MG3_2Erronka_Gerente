package Klaseak;

public class ProduktuaOsagaia {
    private int osagaiaId;
    private int kantitatea;
    private String izena;
    private int stock;

    public int getOsagaiaId() { return osagaiaId; }
    public void setOsagaiaId(int osagaiaId) { this.osagaiaId = osagaiaId; }

    public int getKantitatea() { return kantitatea; }
    public void setKantitatea(int kantitatea) { this.kantitatea = kantitatea; }

    public String getIzena() { return izena; }
    public void setIzena(String izena) { this.izena = izena; }

    public int getStock() { return stock; }
    public void setStock(int stock) { this.stock = stock; }
}
